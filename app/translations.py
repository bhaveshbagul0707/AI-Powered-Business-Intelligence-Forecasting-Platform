def translate(language: str, key: str, **values: Any) -> str:
    """Translate an interface string, falling back to English if not provided."""
    template = _TRANSLATIONS.get(language, {}).get(key, _ENGLISH.get(key, key))
    return template.format(**values) if values else template


def month_names(language: str) -> list[str]:
    return _MONTHS.get(
        language,
        ["January", "February", "March", "April", "May", "June",
         "July", "August", "September", "October", "November", "December"],
    )


def chart_text(language: str, key: str) -> str:
    """Return a translated chart label for the requested chart key."""
    indexes = {
        "chart_trend": 0,
        "chart_category": 1,
        "chart_region": 2,
        "chart_customer": 3,
        "chart_sales": 4,
        "chart_profit": 5,
        "chart_discount": 6,
        "chart_shipping": 7,
        "chart_discount_profit": 8,
    }
    row = _CHART_TEXT.get(language, _CHART_TEXT["English"])
    return row[indexes[key]]


